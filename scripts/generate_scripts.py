#!/usr/bin/env python3
"""Render preview training scripts from scripts/script_manifest.json.

This generator is intentionally preview-only: existing scripts remain the
source of truth until the rendered commands match them and the migration is
reviewed separately.
"""

from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MANIFEST = REPO_ROOT / "scripts" / "script_manifest.json"


def load_manifest(path: Path) -> dict:
    return json.loads(path.read_text())


def command_tokens(command: dict) -> list[str]:
    return [*command["launcher"], command["main"], *command["argv"]]


def render_command(command: dict) -> str:
    return shlex.join(command_tokens(command))


def render_script(entry: dict, manifest_path: Path) -> str:
    lines = [
        "#!/bin/bash",
        "",
        f"# Generated preview from {manifest_path.as_posix()}.",
        "# Existing scripts remain authoritative; do not edit this file by hand.",
        "",
    ]
    for index, command in enumerate(entry["commands"]):
        if index:
            lines.append("")
        lines.append(render_command(command))
    return "\n".join(lines) + "\n"


def ensure_preview_output_dir(output_dir: Path) -> None:
    scripts_dir = (REPO_ROOT / "scripts").resolve()
    resolved = output_dir.resolve()
    if resolved == scripts_dir:
        raise SystemExit("Refusing to write generated previews over scripts/.")
    output_dir.mkdir(parents=True, exist_ok=True)


def write_generated_scripts(manifest: dict, manifest_path: Path, output_dir: Path, force: bool) -> list[Path]:
    ensure_preview_output_dir(output_dir)
    written = []
    for entry in manifest["entries"]:
        if entry.get("metadata_only"):
            continue
        target = output_dir / entry["path"]
        if target.exists() and not force:
            raise SystemExit(f"Refusing to overwrite existing generated preview: {target}")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_script(entry, manifest_path))
        written.append(target)
    return written


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--force", action="store_true", help="Overwrite files in the preview output directory.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    manifest_path = args.manifest.resolve()
    manifest = load_manifest(manifest_path)
    written = write_generated_scripts(manifest, manifest_path, args.output_dir, args.force)
    print(f"Generated {len(written)} preview scripts in {args.output_dir}")


if __name__ == "__main__":
    main()
